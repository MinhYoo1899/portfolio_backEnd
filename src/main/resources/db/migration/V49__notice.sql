-- 설계(2026-07-08, 화면정의서 공지사항 §1/§2/§4/§5 확정값):
--   상태 라이프사이클 NOTICE_STTS_CD = DRAFT/SCHEDULED/PUBLISHED_ONGOING/CLOSED (저장·전이).
--     생성: saveAsDraft→DRAFT / sendTiming=SCHEDULED→SCHEDULED / IMMEDIATE→PUBLISHED_ONGOING(발행+알림).
--     cron(1분): SCHEDULED 중 scheduledAt<=now → PUBLISHED_ONGOING 전이 + 알림 발송(스텁). 수동종료: PUBLISHED_ONGOING→CLOSED.
--   대상 target = ALL/ALL_PARTNER/MEMBER/SPECIFIC_PARTNER. 알림 = 앱푸시(FCM) 단일 — FCM 미설정 시 발송 스텁(NOTIFY_SEND_YN만 기록).
--   권한 NOTICE_VIEW/NOTICE_MNG(STAFF↑, CONTENT 패턴). 명명·감사5·CK·utf8mb4_0900. seed 재실행 안전.
-- =============================================================================

CREATE TABLE NOTICE (
    NOTICE_SN        BIGINT       NOT NULL AUTO_INCREMENT COMMENT '공지일련번호',
    TITLE            VARCHAR(200) NOT NULL                COMMENT '제목',
    CONTENT          MEDIUMTEXT   NOT NULL                COMMENT '내용',
    TARGET_TYPE_CD   VARCHAR(30)  NOT NULL                COMMENT '대상(ALL/ALL_PARTNER/MEMBER/SPECIFIC_PARTNER)',
    SEND_TIMING_CD   VARCHAR(20)  NOT NULL DEFAULT 'IMMEDIATE' COMMENT '발송시점(IMMEDIATE/SCHEDULED)',
    SCHEDULED_AT     DATETIME(6)  NULL                    COMMENT '예약 발송 일시(SCHEDULED 시)',
    PUBLISHED_AT     DATETIME(6)  NULL                    COMMENT '발행 일시',
    NOTICE_STTS_CD   VARCHAR(30)  NOT NULL                COMMENT '상태(DRAFT/SCHEDULED/PUBLISHED_ONGOING/CLOSED)',
    NOTIFY_SEND_YN   CHAR(1)      NOT NULL DEFAULT 'N'    COMMENT '알림 발송 여부',
    REG_DT           DATETIME(6)  NOT NULL                COMMENT '등록일시',
    RGTR_SN          BIGINT       NULL                    COMMENT '등록자',
    MDFCN_DT         DATETIME(6)  NULL                    COMMENT '수정일시',
    MDFR_SN          BIGINT       NULL                    COMMENT '수정자',
    DEL_YN           CHAR(1)      NOT NULL DEFAULT 'N'    COMMENT '삭제여부(soft delete)',
    PRIMARY KEY (NOTICE_SN),
    KEY IX_NOTICE_STTS (NOTICE_STTS_CD),
    KEY IX_NOTICE_SCHEDULED (NOTICE_STTS_CD, SCHEDULED_AT),
    CONSTRAINT CK_NOTICE_DEL     CHECK (DEL_YN IN ('Y','N')),
    CONSTRAINT CK_NOTICE_NOTIFY  CHECK (NOTIFY_SEND_YN IN ('Y','N')),
    CONSTRAINT CK_NOTICE_STTS    CHECK (NOTICE_STTS_CD IN ('DRAFT','SCHEDULED','PUBLISHED_ONGOING','CLOSED')),
    CONSTRAINT CK_NOTICE_TIMING  CHECK (SEND_TIMING_CD IN ('IMMEDIATE','SCHEDULED')),
    CONSTRAINT CK_NOTICE_TARGET  CHECK (TARGET_TYPE_CD IN ('ALL','ALL_PARTNER','MEMBER','SPECIFIC_PARTNER'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='공지사항';

-- 권한 (AUTH_MST + ROLE_AUTH) — CONTENT 패턴 미러(STAFF↑) -------------------------
INSERT INTO AUTH_MST (AUTH_CD, AUTH_NM, USE_YN, REG_DT)
SELECT 'NOTICE_VIEW', '공지 조회(운영자)', 'Y', UTC_TIMESTAMP(6)
 WHERE NOT EXISTS (SELECT 1 FROM AUTH_MST WHERE AUTH_CD = 'NOTICE_VIEW' AND DEL_YN = 'N');

INSERT INTO AUTH_MST (AUTH_CD, AUTH_NM, USE_YN, REG_DT)
SELECT 'NOTICE_MNG', '공지 관리(운영자 — 작성/수정/삭제/종료)', 'Y', UTC_TIMESTAMP(6)
 WHERE NOT EXISTS (SELECT 1 FROM AUTH_MST WHERE AUTH_CD = 'NOTICE_MNG' AND DEL_YN = 'N');

INSERT INTO ROLE_AUTH (ROLE_SN, AUTH_SN, REG_DT)
SELECT R.ROLE_SN, A.AUTH_SN, UTC_TIMESTAMP(6)
  FROM ROLE_MST R
  JOIN AUTH_MST A
    ON (R.ROLE_CD = 'OPERATOR_STAFF'      AND A.AUTH_CD IN ('NOTICE_VIEW','NOTICE_MNG'))
    OR (R.ROLE_CD = 'OPERATOR_SUPERVISOR' AND A.AUTH_CD IN ('NOTICE_VIEW','NOTICE_MNG'))
 WHERE R.DEL_YN = 'N' AND A.DEL_YN = 'N'
   AND NOT EXISTS (SELECT 1 FROM ROLE_AUTH RA
                    WHERE RA.ROLE_SN = R.ROLE_SN AND RA.AUTH_SN = A.AUTH_SN AND RA.DEL_YN = 'N');
