-- =============================================================================
-- V22 : USER 메뉴 '문의'를 비로그인에도 노출 (LGN_NEED_YN 'Y' → 'N')
-- 사유(사용자 확정 2026-06-25): 문의 게시판은 목록/상세가 비로그인 공개(작성만 로그인 필요).
--   따라서 사이드바에 항상 노출되어야 함. 기존엔 LGN_NEED_YN='Y'라 비로그인 시 숨겨졌음.
-- 범위: USER 채널 '/inquiries' 1행만.
-- =============================================================================

UPDATE MENU_INFO
   SET LGN_NEED_YN = 'N', MDFCN_DT = NOW(6)
 WHERE MENU_CHNL_CD = 'USER'
   AND DEL_YN = 'N'
   AND URL_ADDR = '/inquiries';
