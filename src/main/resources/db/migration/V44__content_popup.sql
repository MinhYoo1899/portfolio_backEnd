-- 1) 팝업 테이블 ---------------------------------------------------------------
CREATE TABLE CONTENT_POPUP (
    CONTENT_POPUP_SN   BIGINT       NOT NULL AUTO_INCREMENT COMMENT '팝업일련번호',
    IMG_URL            VARCHAR(500) NOT NULL                COMMENT '팝업이미지 URL(자체 파일인프라 반환 경로)',
    TITLE              VARCHAR(200) NOT NULL                COMMENT '팝업 제목',
    EXPOSE_LOCATION_CD VARCHAR(50)  NOT NULL                COMMENT '노출위치(COMM_CD.GROUP_CD=POPUP_EXPOSE_LOCATION)',
    EXPOSE_TARGET_CD   VARCHAR(50)  NOT NULL                COMMENT '노출대상(COMM_CD.GROUP_CD=POPUP_EXPOSE_TARGET)',
    LINK_TARGET_CD     VARCHAR(50)  NULL                    COMMENT '연결대상코드(CONTENT_LINK_TARGET 재사용)',
    LINK_TARGET_VAL    VARCHAR(500) NULL                    COMMENT '연결대상값',
    EXPOSE_BGN_DATE    DATE         NULL                    COMMENT '노출시작일(KST)',
    EXPOSE_END_DATE    DATE         NULL                    COMMENT '노출종료일(KST)',
    EXPOSE_YN          CHAR(1)      NOT NULL DEFAULT 'Y'    COMMENT '노출여부(isActive 토글)',
    REG_DT             DATETIME(6)  NOT NULL                COMMENT '등록일시',
    RGTR_SN            BIGINT       NULL                    COMMENT '등록자(사용자일련번호)',
    MDFCN_DT           DATETIME(6)  NULL                    COMMENT '수정일시',
    MDFR_SN            BIGINT       NULL                    COMMENT '수정자(사용자일련번호)',
    DEL_YN             CHAR(1)      NOT NULL DEFAULT 'N'    COMMENT '삭제여부(soft delete)',
    PRIMARY KEY (CONTENT_POPUP_SN),
    KEY IX_CONTENT_POPUP_EXPOSE (EXPOSE_YN, EXPOSE_BGN_DATE, EXPOSE_END_DATE),
    CONSTRAINT CK_CONTENT_POPUP_EXPOSE_YN CHECK (EXPOSE_YN IN ('Y','N')),
    CONSTRAINT CK_CONTENT_POPUP_DEL       CHECK (DEL_YN IN ('Y','N')),
    CONSTRAINT CK_CONTENT_POPUP_DATE      CHECK (EXPOSE_END_DATE IS NULL OR EXPOSE_BGN_DATE IS NULL OR EXPOSE_END_DATE >= EXPOSE_BGN_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='콘텐츠 팝업';

