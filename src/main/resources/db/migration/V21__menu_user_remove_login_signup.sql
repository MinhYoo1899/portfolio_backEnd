-- V21 : USER 메뉴에서 '로그인'·'회원 가입' 제거 (soft delete)
-- 사유(사용자 확정 2026-06-25): 퍼블리싱상 로그인/회원가입은 사이드바 네비가 아니라
--   상단 헤더 영역에 별도 배치됨 → 메뉴 목록(GNB/사이드바) 항목으로 부적합 → USER 채널에서 제외.
-- 범위: USER 채널만(PARTNER/OPERATOR는 유지). 물리삭제 아닌 DEL_YN='Y'(되돌리기/이력 보존).
-- =============================================================================

UPDATE MENU_INFO
   SET DEL_YN = 'Y', MDFCN_DT = NOW(6)
 WHERE MENU_CHNL_CD = 'USER'
   AND DEL_YN = 'N'
   AND URL_ADDR IN ('/login', '/signup');
