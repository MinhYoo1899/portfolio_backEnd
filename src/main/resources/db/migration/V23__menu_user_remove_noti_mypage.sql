-- V23 : USER 메뉴에서 '알림' + '마이페이지'(하위 6개 포함) 제거 (soft delete)
-- 사유(사용자 확정 2026-06-25): 퍼블리싱상 알림=상단 헤더 벨 아이콘, 마이페이지=하단 GNB 'MY' 로
--   접근 → 사이드바 메뉴 목록 항목으로 부적합. 마이페이지 하위(프로필수정/예약현황/찜/후기/쿠폰/설정)도
--   함께 제거(부모 제거 시 고아가 최상위로 떠오르는 것 방지). 필요 시 마이페이지 내부 서브내비는 별도 처리.
-- 범위: USER 채널만. DEL_YN='Y'(되돌리기/이력 보존).
-- =============================================================================

UPDATE MENU_INFO
   SET DEL_YN = 'Y', MDFCN_DT = NOW(6)
 WHERE MENU_CHNL_CD = 'USER'
   AND DEL_YN = 'N'
   AND (
        URL_ADDR = '/notifications'                       -- 알림
     OR (MENU_NM = '마이페이지' AND URL_ADDR IS NULL)      -- 마이페이지(폴더형 부모)
     OR URL_ADDR LIKE '/mypage/%'                          -- 마이페이지 하위 6개
   );
