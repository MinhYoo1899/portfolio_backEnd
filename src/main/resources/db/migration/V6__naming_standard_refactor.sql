-- ----------------------------------------------------------------------------
-- 1. AUTH 계열 — 생성컬럼·FK 가 개명 대상 컬럼에 의존하므로 해체 → 개명 → 재구성
-- ----------------------------------------------------------------------------
-- 1-1) ROLE_AUTHRT: AUTHRT_SN 의존물 해체 (FK → 유니크/인덱스 → 생성컬럼 순)
ALTER TABLE ROLE_AUTHRT DROP FOREIGN KEY FK_ROLE_AUTHRT_AUTHRT;
ALTER TABLE ROLE_AUTHRT DROP FOREIGN KEY FK_ROLE_AUTHRT_ROLE;
ALTER TABLE ROLE_AUTHRT DROP INDEX UK_ROLE_AUTHRT;
ALTER TABLE ROLE_AUTHRT DROP INDEX IX_ROLE_AUTHRT_AUTHRT;
ALTER TABLE ROLE_AUTHRT DROP COLUMN ACTV_AUTHRT_SN;

-- 1-2) AUTHRT: AUTHRT_CD 의존물 해체
ALTER TABLE AUTHRT DROP INDEX UK_AUTHRT_CD;
ALTER TABLE AUTHRT DROP COLUMN ACTV_AUTHRT_CD;

-- 1-3) 컬럼 개명 (RENAME COLUMN — 데이터·코멘트 보존)
ALTER TABLE ROLE_AUTHRT RENAME COLUMN ROLE_AUTHRT_SN TO ROLE_AUTH_SN;
ALTER TABLE ROLE_AUTHRT RENAME COLUMN AUTHRT_SN TO AUTH_SN;
ALTER TABLE AUTHRT RENAME COLUMN AUTHRT_SN TO AUTH_SN;
ALTER TABLE AUTHRT RENAME COLUMN AUTHRT_CD TO AUTH_CD;
ALTER TABLE AUTHRT RENAME COLUMN AUTHRT_NM TO AUTH_NM;

-- 1-4) 테이블 개명
RENAME TABLE AUTHRT TO AUTH, ROLE_AUTHRT TO ROLE_AUTH;

-- 1-5) 해체했던 것들을 새 이름으로 재구성
-- (FK_ROLE_AUTHRT_ROLE 은 ROLE_SN 의 FK 자동생성 인덱스 — FK drop 후에도 남으므로 새 이름으로 정리,
--  아래 FK_ROLE_AUTH_ROLE 재추가 시 이 인덱스를 재사용함. codex 교차검토 권고 + SHOW INDEX 실확인)
ALTER TABLE ROLE_AUTH RENAME INDEX FK_ROLE_AUTHRT_ROLE TO IX_ROLE_AUTH_ROLE;
ALTER TABLE AUTH
    ADD COLUMN ACTV_AUTH_CD VARCHAR(80) GENERATED ALWAYS AS (CASE WHEN DEL_YN = 'N' THEN AUTH_CD END) VIRTUAL COMMENT '활성행 유니크 제약용 생성컬럼(비업무)',
    ADD UNIQUE KEY UK_AUTH_CD (ACTV_AUTH_CD);
ALTER TABLE ROLE_AUTH
    ADD COLUMN ACTV_AUTH_SN BIGINT GENERATED ALWAYS AS (CASE WHEN DEL_YN = 'N' THEN AUTH_SN END) VIRTUAL COMMENT '활성행 유니크 제약용 생성컬럼(비업무)',
    ADD UNIQUE KEY UK_ROLE_AUTH (ACTV_ROLE_SN, ACTV_AUTH_SN),
    ADD KEY IX_ROLE_AUTH_AUTH (AUTH_SN),
    ADD CONSTRAINT FK_ROLE_AUTH_ROLE FOREIGN KEY (ROLE_SN) REFERENCES ROLE (ROLE_SN),
    ADD CONSTRAINT FK_ROLE_AUTH_AUTH FOREIGN KEY (AUTH_SN) REFERENCES AUTH (AUTH_SN);

-- ----------------------------------------------------------------------------
-- 2. MENU_INFO 필요권한 컬럼 — CHECK 가 컬럼을 참조하므로 해체 → 개명 → 재구성
-- ----------------------------------------------------------------------------
ALTER TABLE MENU_INFO DROP CHECK CK_MENU_INFO_AUTHRT;
ALTER TABLE MENU_INFO RENAME COLUMN AUTHRT_CD TO AUTH_CD;
ALTER TABLE MENU_INFO ADD CONSTRAINT CK_MENU_INFO_AUTH CHECK (LGN_NEED_YN = 'Y' OR AUTH_CD IS NULL);

-- ----------------------------------------------------------------------------
-- 3. 테이블 개명 (단순 RENAME — 데이터·인덱스·FK 보존)
-- ----------------------------------------------------------------------------
RENAME TABLE
    LGN_HSTRY        TO LOGIN_LOG_INFO,
    AUDIT_LOG        TO AUDIT_LOG_INFO,
    PRTNR_APRV_HSTRY TO PARTNER_APPROVE_LOG_INFO,
    TRMS_AGRE        TO TRMS_AGRE_INFO,
    MBL_TELNO_VRFC   TO MBL_TELNO_VRFC_INFO,
    USER_PRFL        TO USER_DTL_INFO,
    MSTR_PRFL        TO MSTR_DTL_INFO,
    COM_CD           TO COMM_CD,
    COM_CD_GROUP     TO COMM_CD_GROUP;

-- ----------------------------------------------------------------------------
-- 4. PK 컬럼 스템 정리 (스템이 바뀐 테이블만)
-- ----------------------------------------------------------------------------
ALTER TABLE LOGIN_LOG_INFO           RENAME COLUMN LGN_HSTRY_SN        TO LOGIN_LOG_SN;
ALTER TABLE PARTNER_APPROVE_LOG_INFO RENAME COLUMN PRTNR_APRV_HSTRY_SN TO PARTNER_APPROVE_LOG_SN;
ALTER TABLE COMM_CD                  RENAME COLUMN COM_CD_SN           TO COMM_CD_SN;
ALTER TABLE COMM_CD_GROUP            RENAME COLUMN COM_CD_GROUP_SN     TO COMM_CD_GROUP_SN;
-- (AUDIT_LOG_SN / TRMS_AGRE_SN / MBL_TELNO_VRFC_SN 은 스템 동일 — 유지)

-- ----------------------------------------------------------------------------
-- 5. 인덱스·제약 이름 정리 (스템이 바뀐 것만 — RENAME INDEX 는 무손실, FK/CK 는 drop+add)
-- ----------------------------------------------------------------------------
ALTER TABLE LOGIN_LOG_INFO RENAME INDEX IX_LGN_HSTRY_USER_REG TO IX_LOGIN_LOG_USER_REG;
ALTER TABLE LOGIN_LOG_INFO RENAME INDEX IX_LGN_HSTRY_REG_DT   TO IX_LOGIN_LOG_REG_DT;

ALTER TABLE PARTNER_APPROVE_LOG_INFO RENAME INDEX IX_PRTNR_APRV_HSTRY      TO IX_PARTNER_APPROVE_LOG;
ALTER TABLE PARTNER_APPROVE_LOG_INFO RENAME INDEX IX_PRTNR_APRV_HSTRY_ACTR TO IX_PARTNER_APPROVE_LOG_ACTR;
ALTER TABLE PARTNER_APPROVE_LOG_INFO DROP FOREIGN KEY FK_PRTNR_APRV_HSTRY_PRTNR;
ALTER TABLE PARTNER_APPROVE_LOG_INFO DROP FOREIGN KEY FK_PRTNR_APRV_HSTRY_ACTR;
ALTER TABLE PARTNER_APPROVE_LOG_INFO DROP CHECK CK_PRTNR_APRV_HSTRY_BFR;
ALTER TABLE PARTNER_APPROVE_LOG_INFO DROP CHECK CK_PRTNR_APRV_HSTRY_AFT;
ALTER TABLE PARTNER_APPROVE_LOG_INFO
    ADD CONSTRAINT FK_PARTNER_APPROVE_LOG_PRTNR FOREIGN KEY (PRTNR_SN) REFERENCES PRTNR (PRTNR_SN),
    ADD CONSTRAINT FK_PARTNER_APPROVE_LOG_ACTR FOREIGN KEY (ACTR_USER_SN) REFERENCES USER_ACNT (USER_SN),
    ADD CONSTRAINT CK_PARTNER_APPROVE_LOG_BFR CHECK (BFR_APRV_STTS IS NULL OR BFR_APRV_STTS IN ('REQUESTED','APPROVED','REJECTED')),
    ADD CONSTRAINT CK_PARTNER_APPROVE_LOG_AFT CHECK (AFT_APRV_STTS IN ('REQUESTED','APPROVED','REJECTED'));

ALTER TABLE USER_DTL_INFO DROP FOREIGN KEY FK_USER_PRFL_USER;
ALTER TABLE USER_DTL_INFO ADD CONSTRAINT FK_USER_DTL_INFO_USER FOREIGN KEY (USER_SN) REFERENCES USER_ACNT (USER_SN);
ALTER TABLE MSTR_DTL_INFO DROP FOREIGN KEY FK_MSTR_PRFL_USER;
ALTER TABLE MSTR_DTL_INFO ADD CONSTRAINT FK_MSTR_DTL_INFO_USER FOREIGN KEY (USER_SN) REFERENCES USER_ACNT (USER_SN);

ALTER TABLE COMM_CD       RENAME INDEX UK_COM_CD            TO UK_COMM_CD;
ALTER TABLE COMM_CD       RENAME INDEX IX_COM_CD_GROUP_SORT TO IX_COMM_CD_GROUP_SORT;
ALTER TABLE COMM_CD_GROUP RENAME INDEX UK_COM_CD_GROUP      TO UK_COMM_CD_GROUP;
