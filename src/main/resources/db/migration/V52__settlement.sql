-- V52 : 정산 관리 — 정산설정(SETTLEMENT_SETTING 단일행) + 파트너정산 실행기록(PARTNER_SETTLEMENT) + 권한
-- 설계(2026-07-08, 화면정의서 정산 §1/§2/§4/§5 확정값):
--   결제현황·매출통계 = 기존 PAYMENT/RESERVATION 집계(조회). 수수료율은 정산설정값(더미로 개발 후 실값 교체).
--   파트너정산 = 회차(월)별 파트너 판매금 집계 + 수수료 차감(설정값) → 정산예정금 산출(조회). "정산하기"=수동확정
--     (계좌이체는 오프라인, 시스템은 상태만 WAITING→COMPLETED). 실행 기록 = PARTNER_SETTLEMENT(회차·파트너 UNIQUE).
--   정산설정 저장/초기화 = SUPERVISOR(민감). 조회 = STAFF↑. 자동 PG송금 없음.
--   권한 SETTLEMENT_VIEW(STAFF↑)/SETTLEMENT_MNG(SUPERVISOR). 명명·감사·CK·utf8mb4_0900.
-- =============================================================================

-- 1) 정산 설정(단일행 SN=1) — 수수료율/정산주기/명세발행 -------------------------
CREATE TABLE SETTLEMENT_SETTING (
    SETTLEMENT_SETTING_SN BIGINT      NOT NULL             COMMENT '설정일련번호(단일행=1)',
    PLATFORM_FEE_RATE     DECIMAL(5,2) NOT NULL DEFAULT 15.00 COMMENT '플랫폼 수수료율(%)',
    CARD_FEE_RATE         DECIMAL(5,2) NOT NULL DEFAULT 3.00  COMMENT '카드 수수료율(%)',
    VAT_RATE              DECIMAL(5,2) NOT NULL DEFAULT 10.00 COMMENT '부가세율(%)',
    SETTLEMENT_BASIS_CD   VARCHAR(20)  NOT NULL DEFAULT 'CHECKOUT_DATE' COMMENT '정산기준(CHECKOUT_DATE/CONFIRMED_DATE)',
    DEPOSIT_DUE_DAYS      INT          NOT NULL DEFAULT 5   COMMENT '입금 예정일(기준일 +N일)',
    SETTLEMENT_CYCLE_CD   VARCHAR(20)  NOT NULL DEFAULT 'MONTHLY' COMMENT '정산주기(MONTHLY/WEEKLY/DAILY)',
    MIN_SETTLEMENT_AMT    INT          NOT NULL DEFAULT 10000 COMMENT '최소 정산 금액(원, 미만 이월)',
    AUTO_INVOICE_YN       CHAR(1)      NOT NULL DEFAULT 'Y' COMMENT '자동 명세서 발행',
    TAX_INVOICE_YN        CHAR(1)      NOT NULL DEFAULT 'Y' COMMENT '세금계산서 발행',
    REG_DT                DATETIME(6)  NOT NULL             COMMENT '등록일시',
    RGTR_SN               BIGINT       NULL                 COMMENT '등록자',
    MDFCN_DT              DATETIME(6)  NULL                 COMMENT '수정일시',
    MDFR_SN               BIGINT       NULL                 COMMENT '수정자',
    PRIMARY KEY (SETTLEMENT_SETTING_SN),
    CONSTRAINT CK_SETTLEMENT_BASIS  CHECK (SETTLEMENT_BASIS_CD IN ('CHECKOUT_DATE','CONFIRMED_DATE')),
    CONSTRAINT CK_SETTLEMENT_CYCLE  CHECK (SETTLEMENT_CYCLE_CD IN ('MONTHLY','WEEKLY','DAILY')),
    CONSTRAINT CK_SETTLEMENT_AUTO   CHECK (AUTO_INVOICE_YN IN ('Y','N')),
    CONSTRAINT CK_SETTLEMENT_TAX    CHECK (TAX_INVOICE_YN IN ('Y','N')),
    CONSTRAINT CK_SETTLEMENT_RATES  CHECK (PLATFORM_FEE_RATE >= 0 AND CARD_FEE_RATE >= 0 AND VAT_RATE >= 0),
    CONSTRAINT CK_SETTLEMENT_DAYS   CHECK (DEPOSIT_DUE_DAYS >= 0 AND MIN_SETTLEMENT_AMT >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='정산 설정(단일행)';

INSERT INTO SETTLEMENT_SETTING (SETTLEMENT_SETTING_SN, REG_DT, MDFCN_DT)
SELECT 1, UTC_TIMESTAMP(6), UTC_TIMESTAMP(6)
 WHERE NOT EXISTS (SELECT 1 FROM SETTLEMENT_SETTING WHERE SETTLEMENT_SETTING_SN = 1);

-- 2) 파트너 정산 실행기록 — 회차(월)·파트너 UNIQUE. 실행 시점 스냅샷 -----------------
CREATE TABLE PARTNER_SETTLEMENT (
    PARTNER_SETTLEMENT_SN BIGINT      NOT NULL AUTO_INCREMENT COMMENT '파트너정산일련번호',
    ROUND_YM              CHAR(7)     NOT NULL              COMMENT '정산 회차(YYYY-MM)',
    PRTNR_SN              BIGINT      NOT NULL              COMMENT '파트너일련번호',
    TOTAL_SALES_AMT       INT         NOT NULL DEFAULT 0    COMMENT '총 판매금(스냅샷)',
    CARD_FEE_AMT          INT         NOT NULL DEFAULT 0    COMMENT '카드 수수료(스냅샷)',
    PLATFORM_FEE_AMT      INT         NOT NULL DEFAULT 0    COMMENT '플랫폼 수수료(스냅샷)',
    SETTLEMENT_AMT        INT         NOT NULL DEFAULT 0    COMMENT '정산금(스냅샷)',
    SETTLEMENT_STTS_CD    VARCHAR(20) NOT NULL DEFAULT 'COMPLETED' COMMENT '정산상태(COMPLETED)',
    EXECUTED_AT           DATETIME(6) NULL                  COMMENT '정산 실행일시',
    REG_DT                DATETIME(6) NOT NULL              COMMENT '등록일시',
    RGTR_SN               BIGINT      NULL                  COMMENT '등록자(실행자)',
    MDFCN_DT              DATETIME(6) NULL                  COMMENT '수정일시',
    MDFR_SN               BIGINT      NULL                  COMMENT '수정자',
    PRIMARY KEY (PARTNER_SETTLEMENT_SN),
    UNIQUE KEY UX_PARTNER_SETTLEMENT (ROUND_YM, PRTNR_SN),
    CONSTRAINT CK_PARTNER_SETTLEMENT_STTS CHECK (SETTLEMENT_STTS_CD IN ('COMPLETED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='파트너 정산 실행기록';

-- 3) 정산 권한 (AUTH_MST + ROLE_AUTH) — VIEW=STAFF↑, MNG=SUPERVISOR ------------------
INSERT INTO AUTH_MST (AUTH_CD, AUTH_NM, USE_YN, REG_DT)
SELECT 'SETTLEMENT_VIEW', '정산 조회(운영자)', 'Y', UTC_TIMESTAMP(6)
 WHERE NOT EXISTS (SELECT 1 FROM AUTH_MST WHERE AUTH_CD = 'SETTLEMENT_VIEW' AND DEL_YN = 'N');

INSERT INTO AUTH_MST (AUTH_CD, AUTH_NM, USE_YN, REG_DT)
SELECT 'SETTLEMENT_MNG', '정산 관리(SUPERVISOR — 정산실행/설정)', 'Y', UTC_TIMESTAMP(6)
 WHERE NOT EXISTS (SELECT 1 FROM AUTH_MST WHERE AUTH_CD = 'SETTLEMENT_MNG' AND DEL_YN = 'N');

INSERT INTO ROLE_AUTH (ROLE_SN, AUTH_SN, REG_DT)
SELECT R.ROLE_SN, A.AUTH_SN, UTC_TIMESTAMP(6)
  FROM ROLE_MST R
  JOIN AUTH_MST A
    ON (R.ROLE_CD = 'OPERATOR_STAFF'      AND A.AUTH_CD = 'SETTLEMENT_VIEW')
    OR (R.ROLE_CD = 'OPERATOR_SUPERVISOR' AND A.AUTH_CD IN ('SETTLEMENT_VIEW','SETTLEMENT_MNG'))
 WHERE R.DEL_YN = 'N' AND A.DEL_YN = 'N'
   AND NOT EXISTS (SELECT 1 FROM ROLE_AUTH RA
                    WHERE RA.ROLE_SN = R.ROLE_SN AND RA.AUTH_SN = A.AUTH_SN AND RA.DEL_YN = 'N');
